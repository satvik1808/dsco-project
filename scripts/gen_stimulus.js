// Generates the random button presses for the simulation, one entry per clock:
//   build/stimulus.v : Verilog lines `include'd by the testbench
//   build/stim.hex   : the same, one 32-bit word {hall_up, hall_dn, car_btn0, car_btn1}
//                      per line, read by the JS checks and the website replay
// Usage: node scripts/gen_stimulus.js [cycles] [seed]
const fs = require('fs');
const path = require('path');

const CYCLES = parseInt(process.argv[2] || '4000', 10);
let seed = parseInt(process.argv[3] || '2026', 10) >>> 0;
const N = 8;

function rand() { // mulberry32
  seed = (seed + 0x6D2B79F5) >>> 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const floor = () => Math.floor(rand() * N);

const lines = [], vlines = [];
const h2 = v => "8'h" + v.toString(16).padStart(2, '0');
for (let c = 0; c < CYCLES; c++) {
  let up = 0, dn = 0, c0 = 0, c1 = 0;
  if (rand() < 0.035) { const f = floor(); if (f < N - 1) up |= 1 << f; }
  if (rand() < 0.035) { const f = floor(); if (f > 0) dn |= 1 << f; }
  if (rand() < 0.015) c0 |= 1 << floor();
  if (rand() < 0.015) c1 |= 1 << floor();
  const word = ((up << 24) | (dn << 16) | (c0 << 8) | c1) >>> 0;
  lines.push(word.toString(16).padStart(8, '0'));
  vlines.push(`hall_up_btn = ${h2(up)}; hall_dn_btn = ${h2(dn)}; car_btn0 = ${h2(c0)}; car_btn1 = ${h2(c1)}; #10;  // cycle ${c}`);
}

const out = path.join(__dirname, '..', 'build', 'stim.hex');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n') + '\n');
fs.writeFileSync(path.join(path.dirname(out), 'stimulus.v'),
  `// Generated by scripts/gen_stimulus.js (${CYCLES} clock cycles). Do not edit.\n` + vlines.join('\n') + '\n');
console.log(`wrote ${CYCLES} cycles of stimulus to build/stimulus.v and build/stim.hex`);
