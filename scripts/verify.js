// Checks the Verilog simulation (build/elevator.vcd):
//   1. Liveness: every hall call is answered within MAX_WAIT clock cycles.
//   2. Co-simulation: the website's JavaScript model (web/elevator_rtl.js),
//      run on the same button presses, has exactly the same register values
//      as the Verilog on every clock cycle.
// On success, writes web/verilog_trace.js so the website can replay the
// actual Icarus Verilog simulation.
const fs = require('fs');
const path = require('path');
const ElevatorRTL = require('../web/elevator_rtl.js');
const { read, T, unpack } = require('./vcd.js');

const MAX_WAIT = 600;
const root = path.join(__dirname, '..');
const vcd = read(path.join(root, 'build/elevator.vcd'));
const stim = fs.readFileSync(path.join(root, 'build/stim.hex'), 'utf8')
  .trim().split('\n').map(h => parseInt(h, 16));

const FIELDS = ['cycle',
  'floor0', 'state0', 'dir0', 'timer0', 'calls0',
  'floor1', 'state1', 'dir1', 'timer1', 'calls1',
  'up_pend', 'up_asgd', 'up_owner', 'dn_pend', 'dn_asgd', 'dn_owner'];

// register values after each clock edge, read from the testbench wires (tb.floor0, ...)
const rows = [];
for (let c = 0; c < stim.length && T(c + 1) < vcd.endTime; c++)
  rows.push([c].concat(FIELDS.slice(1).map(f => vcd.valueAt(vcd.chanOf['tb.' + f], T(c + 1) + 1))));

// ---- 1. liveness ----
let served = 0, maxWait = 0, starved = 0;
const age = { up_pend: new Array(8).fill(0), dn_pend: new Array(8).fill(0) };
for (const row of rows) {
  for (const reg of ['up_pend', 'dn_pend']) {
    const v = row[FIELDS.indexOf(reg)];
    for (let k = 0; k < 8; k++) {
      if ((v >> k) & 1) age[reg][k]++;
      else if (age[reg][k]) { served++; maxWait = Math.max(maxWait, age[reg][k]); age[reg][k] = 0; }
      if (age[reg][k] > MAX_WAIT) { starved++; console.log(`STARVED cycle ${row[0]}: ${reg} floor ${k}`); age[reg][k] = 0; }
    }
  }
}
console.log(`Simulated ${rows.length} cycles, ${served} hall calls served, longest wait ${maxWait} cycles`);

// ---- 2. JS model vs Verilog ----
const m = ElevatorRTL.create();
let mismatches = 0;
for (let c = 0; c < rows.length; c++) {
  const r = m.step(unpack(stim[c]));
  const js = [c,
    r.cars[0].floor, r.cars[0].state, r.cars[0].dir, r.cars[0].timer, r.cars[0].calls,
    r.cars[1].floor, r.cars[1].state, r.cars[1].dir, r.cars[1].timer, r.cars[1].calls,
    r.up_pend, r.up_asgd, r.up_owner, r.dn_pend, r.dn_asgd, r.dn_owner];
  for (let i = 0; i < FIELDS.length; i++) {
    if (js[i] !== rows[c][i]) {
      if (mismatches < 20) console.log(`MISMATCH cycle ${c} ${FIELDS[i]}: verilog=${rows[c][i]} js=${js[i]}`);
      mismatches++;
    }
  }
}

if (mismatches || starved) {
  console.log(`FAIL: ${mismatches} mismatching values, ${starved} starved hall calls`);
  process.exit(1);
}
console.log(`PASS: every hall call answered; JS model matches Verilog on all ${rows.length} cycles x ${FIELDS.length - 1} registers`);

const outFile = path.join(root, 'web/verilog_trace.js');
fs.writeFileSync(outFile,
  '// Generated by scripts/verify.js from the Icarus Verilog simulation. Do not edit.\n' +
  `window.VERILOG_TRACE = ${JSON.stringify({ fields: FIELDS, stim: stim.slice(0, rows.length), rows })};\n`);
console.log('wrote web/verilog_trace.js for the website replay mode');
