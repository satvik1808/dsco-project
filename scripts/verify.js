// Co-simulation check: runs the JavaScript RTL model (web/elevator_rtl.js) on
// the same stimulus as the Verilog testbench and compares every register on
// every clock cycle against build/trace_verilog.txt.
// On success, writes web/verilog_trace.js so the website can replay the
// actual Icarus Verilog simulation.
const fs = require('fs');
const path = require('path');
const ElevatorRTL = require('../web/elevator_rtl.js');

const root = path.join(__dirname, '..');
const stim = fs.readFileSync(path.join(root, 'build/stim.hex'), 'utf8')
  .trim().split('\n').map(h => parseInt(h, 16));
const trace = fs.readFileSync(path.join(root, 'build/trace_verilog.txt'), 'utf8')
  .trim().split('\n').map(l => l.trim().split(/\s+/).map((v, i) => i === 0 ? parseInt(v, 10) : parseInt(v, 16)));

const FIELDS = ['cycle',
  'floor0', 'state0', 'dir0', 'timer0', 'calls0',
  'floor1', 'state1', 'dir1', 'timer1', 'calls1',
  'up_pend', 'up_asgd', 'up_owner', 'dn_pend', 'dn_asgd', 'dn_owner'];

const unpack = w => ({ hall_up: (w >>> 24) & 255, hall_dn: (w >>> 16) & 255, car0: (w >>> 8) & 255, car1: w & 255 });

const m = ElevatorRTL.create();
let mismatches = 0;
for (let c = 0; c < trace.length; c++) {
  const r = m.step(unpack(stim[c]));
  const js = [c,
    r.cars[0].floor, r.cars[0].state, r.cars[0].dir, r.cars[0].timer, r.cars[0].calls,
    r.cars[1].floor, r.cars[1].state, r.cars[1].dir, r.cars[1].timer, r.cars[1].calls,
    r.up_pend, r.up_asgd, r.up_owner, r.dn_pend, r.dn_asgd, r.dn_owner];
  for (let i = 0; i < FIELDS.length; i++) {
    if (js[i] !== trace[c][i]) {
      if (mismatches < 20) console.log(`MISMATCH cycle ${c} ${FIELDS[i]}: verilog=${trace[c][i]} js=${js[i]}`);
      mismatches++;
    }
  }
}

if (mismatches) {
  console.log(`FAIL: ${mismatches} mismatching values`);
  process.exit(1);
}
console.log(`PASS: JS model matches Verilog on all ${trace.length} cycles x ${FIELDS.length - 1} registers`);

const outFile = path.join(root, 'web/verilog_trace.js');
fs.writeFileSync(outFile,
  '// Generated by scripts/verify.js from the Icarus Verilog simulation. Do not edit.\n' +
  `window.VERILOG_TRACE = ${JSON.stringify({ fields: FIELDS, stim, rows: trace })};\n`);
console.log('wrote web/verilog_trace.js for the website replay mode');
